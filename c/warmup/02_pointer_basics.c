/* ============================================================
 * 第 2 课：指针 = 一个专门用来存"柜子编号"的变量
 * ============================================================
 *
 * 上一课我们有了 &x（x 的柜子编号）。
 * 但编号本身也是个数字，也可以存起来 —— 存编号的变量就叫"指针"。
 *
 *   int  x = 5;       x 是"存整数的柜子"
 *   int *p = &x;      p 是"存柜子编号的柜子"，里面存着 x 的编号
 *
 * 两个符号，方向相反，一定要分清：
 *   &x   取地址：从"名字" -> "编号"      (& 读作 address-of)
 *   *p   解引用：从"编号" -> "那个柜子"  (* 读作 "顺着编号去看")
 *
 * 所以 *(&x) 就等于 x。绕一圈回来了。
 */
#include <stdio.h>

int main(void)
{
    int x = 5;

    /* 定义一个指针。星号写在类型这边：int *p 读作"p 是指向 int 的指针"。
     * 也就是：p 里存的编号，指向的那个柜子群里放的是 int。 */
    int *p = &x;      /* 把 x 的编号存进 p */

    printf("=== 2.1 p 里存的就是 x 的编号 ===\n");
    printf("  x  = %d       <- x 柜子里的内容\n", x);
    printf("  &x = %p       <- x 的柜子编号\n", (void *) &x);
    printf("  p  = %p       <- p 柜子里存的内容(正是上面那个编号)\n", (void *) p);
    printf("  &p = %p       <- p 自己也是变量，它也有自己的编号\n", (void *) &p);

    printf("\n=== 2.2 *p 顺着编号去看那个柜子 ===\n");
    printf("  *p = %d       <- 和 x 一模一样\n", *p);
    printf("  *(&x) = %d    <- 取编号再顺回去，等于 x 本身\n", *(&x));

    printf("\n=== 2.3 通过 *p 可以改 x（关键！）===\n");
    printf("  改之前 x = %d\n", x);
    *p = 99;              /* 意思是：顺着 p 里的编号找到那个柜子，把内容改成 99 */
    printf("  执行 *p = 99 之后 x = %d   <- 我们没碰 x 这个名字，但它变了\n", x);
    printf("  这就是指针的全部意义：拿到编号，就能改那个柜子\n");

    printf("\n=== 2.4 指针自己占多少柜子 ===\n");
    /* 编号在 64 位机器上是个 8 字节的大整数，所以任何指针都占 8 字节 */
    char   c;  char   *pc = &c;
    double dd; double *pd = &dd;
    printf("  int*    占 %zu 字节\n", sizeof(p));
    printf("  char*   占 %zu 字节\n", sizeof(pc));
    printf("  double* 占 %zu 字节\n", sizeof(pd));
    printf("  ^ 都是 8：不管指向啥，存的都只是一个编号\n");

    printf("\n=== 2.5 NULL：空指针 ===\n");
    /* NULL 是特殊编号 0，约定表示"我现在没指向任何东西"。
     * 对 NULL 做 *p 会让程序崩溃（段错误 Segmentation fault）。 */
    int *q = NULL;
    printf("  q = %p  (就是 0)\n", (void *) q);
    // 这里使用 q == NULL 而不是 使用 *q == NULL，可以理解 q 其实是 int * 类型，是指针，即 q 才是指针，
    // *q 表示的这个地址中存的值，即 int 值，例如: int *q = &x; q表示指向x首地址的指针，*q实际是int类型，表示从这个首指针取4字节，这4字节存的值
    if (q == NULL)
        printf("  用之前先判断 q == NULL，是 C 里最基本的自保动作\n");
    /* printf("%d", *q);   <- 千万别，这行会让程序当场崩溃 */

    printf("\n=== 2.6 指针 +1 是加一个元素，不是加 1 字节 ===\n");
    int arr[4] = {11, 22, 33, 44};
    int *pa = &arr[0];          /* 指向第 0 个元素 */
    printf("  pa   = %p, *pa   = %d\n", (void *) pa, *pa);
    // 因为 pa 是 int * 类型，所以 pa+1 表示的是 pa指向的地址再+1 int长度的下一个地址
    printf("  pa+1 = %p, *(pa+1) = %d   <- 编号 +4，因为一个 int 占 4 柜子\n",
           (void *) (pa + 1), *(pa + 1));
    printf("  pa+2 = %p, *(pa+2) = %d\n", (void *) (pa + 2), *(pa + 2));
    printf("  其实 arr[2] 就是 *(arr+2) 的简写，方括号只是语法糖\n");
    printf("  arr[2] = %d, *(arr+2) = %d\n", arr[2], *(arr + 2));

    return 0;
}

/* ------------------------------------------------------------
 * 画面（假设 x 在 100 号柜，p 在 200 号柜）：
 *
 *   编号 100: [    5    ]  <- x，存的是数据
 *   编号 200: [   100   ]  <- p，存的是"100"这个编号
 *
 *   x   = 5      读 100 号柜的内容
 *   &x  = 100    x 的编号
 *   p   = 100    读 200 号柜的内容（正好是 100）
 *   *p  = 5      顺着 p 里的 100 跑过去，读到 5
 *   *p = 99      顺着过去，把 100 号柜改成 99   ==>  x 变成 99
 *
 * 只要记住 "* 就是顺着编号跑过去"，指针就不神秘了。
 * ------------------------------------------------------------ */
