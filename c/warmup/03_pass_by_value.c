/* ============================================================
 * 第 3 课：函数 + 值传递（为什么非要用指针）
 * ============================================================
 *
 * 函数就是"起了名字的一段步骤"，可以反复调用。
 *
 *   int add(int a, int b) { return a + b; }
 *   ^     ^      ^
 *   |     |      +-- 参数：调用时要给的东西
 *   |     +--------- 函数名
 *   +--------------- 返回值类型：算完交回一个 int
 *
 * C 最重要的规则：**值传递**
 *   调用函数时，参数是"复印一份"送进去的。
 *   函数里怎么改，都只是改复印件，原件不动。
 *   ==> 想改原件，就只能把"原件的柜子编号"送进去，也就是传指针。
 */
#include <stdio.h>

/* --- 3.1 普通函数：有返回值 --- */
int add(int a, int b)
{
    return a + b;
}

/* --- 3.2 void 表示"不返回任何东西" --- */
void say_hello(void)
{
    printf("  hello!\n");
}

/* --- 3.3 值传递：改不动调用方 --- */
void try_change(int n)
{
    printf("  [函数内] 进来时 n = %d，n 的地址 = %p\n", n, (void *) &n);
    n = 999;
    printf("  [函数内] 改成了 n = %d\n", n);
    /* 函数一结束，这个 n（复印件）就消失了 */
}

/* --- 3.4 传指针：能改调用方 --- */
void real_change(int *p)
{
    printf("  [函数内] 收到编号 p = %p\n", (void *) p);
    *p = 999;               /* 顺着编号跑回调用方那块柜子，改它 */
    printf("  [函数内] 已经把那个柜子改成 999\n");
}

/* --- 3.5 一个函数想返回两个结果，就用指针"出参" --- */
/* 返回值用来说"成功了没"，真正的结果从指针参数写出去 */
int divide(int a, int b, int *quotient, int *remainder)
{
    if (b == 0)
        return 0;               /* 0 表示失败 */
    *quotient  = a / b;         /* 把商写进调用方的柜子 */
    *remainder = a % b;         /* 把余数写进调用方的柜子 */
    return 1;                   /* 1 表示成功 */
}

int main(void)
{
    printf("=== 3.1 调用函数 ===\n");
    int s = add(3, 4);
    printf("  add(3, 4) = %d\n", s);
    say_hello();

    printf("\n=== 3.3 值传递改不动（重点）===\n");
    int x = 10;
    printf("  [main] 调用前 x = %d，x 的地址 = %p\n", x, (void *) &x);
    try_change(x);
    printf("  [main] 调用后 x = %d   <- 没变！\n", x);
    printf("  ^ 看上面两个地址：函数里的 n 和 main 里的 x 是两个不同的柜子\n");

    printf("\n=== 3.4 传编号就能改 ===\n");
    printf("  [main] 调用前 x = %d\n", x);
    real_change(&x);            /* 注意这里传的是 &x，不是 x */
    printf("  [main] 调用后 x = %d   <- 变了！\n", x);

    printf("\n=== 3.5 用出参返回多个结果 ===\n");
    int q = -1, r = -1;         /* 先准备两个空柜子 */
    if (divide(17, 5, &q, &r))  /* 把两个柜子的编号交给函数 */
        printf("  17 / 5 = %d 余 %d\n", q, r);

    q = -1; r = -1;
    if (!divide(17, 0, &q, &r))
        printf("  17 / 0 -> 函数返回失败，q/r 保持 %d/%d 没被动过\n", q, r);

    printf("\n=== 3.6 数组是例外：传数组等于传编号 ===\n");
    /* 数组名本身就代表"第一个元素的编号"，所以数组"看起来"能被函数改。
     * 其实并不是例外——传的还是编号的复印件，只是编号指向同一块柜子。 */
    int arr[3] = {1, 2, 3};
    printf("  改之前 arr[0] = %d\n", arr[0]);
    real_change(arr);           /* arr 就是 &arr[0]，类型正好是 int* */
    printf("  改之后 arr[0] = %d\n", arr[0]);

    return 0;
}

/* ------------------------------------------------------------
 * 一句话总结这一课：
 *
 *   f(x)   -> 函数拿到的是 x 的复印件，改不动 x
 *   f(&x)  -> 函数拿到的是 x 的柜子编号，用 *p = ... 就能改 x
 *
 * 你之前看到的 "out 参数" 就是这件事的正式叫法：
 * 函数的返回值位置只有一个，不够用，就用指针参数把结果"写出去"。
 * ------------------------------------------------------------ */
