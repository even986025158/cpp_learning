/* ============================================================
 * 第 1 课：内存 = 一条超长的储物柜走廊
 * ============================================================
 *
 * 这个类比后面每一课都要用，务必先建立起来：
 *
 *   内存      = 一条走廊，走廊里排着几十亿个储物柜
 *   1 个柜子  = 1 字节 (byte)
 *   柜子编号  = 地址 (address)，从 0 开始一直往上编
 *   变量      = 你给"某几个连着的柜子"起的名字
 *
 *   int x;    -> 走廊里划走 4 个连着的柜子，起名叫 x
 *   char c;   -> 划走 1 个柜子，起名叫 c
 *   double d; -> 划走 8 个连着的柜子，起名叫 d
 *
 * 两个新符号：
 *   sizeof(x) = "x 占了几个柜子"
 *   &x        = "x 的第一个柜子的编号"     &读作"取地址"
 */
#include <stdio.h>

int main(void)
{
    char   c = 'A';
    int    x = 1000;
    double d = 3.14;

    printf("=== 1.1 各占几个柜子 ===\n");
    printf("  c 占 %zu 个柜子\n", sizeof(c)); //sizeof 返回的是 size_t 类型，unsigned long, 占 8 字节 %zu : u:无符号，z: size_t
    printf("  x 占 %zu 个柜子\n", sizeof(x));
    printf("  d 占 %zu 个柜子\n", sizeof(d));

    /* 打印地址要用 %p (p = pointer 指针)。
     * (void *) 的意思是"我只要这个编号，不关心那里放的是什么类型"。
     * printf 的 %p 规范要求实参必须是 void*，所以固定这么写。
     * 打出来是 0x 开头的十六进制数字，那就是柜子编号。
     * void* 与 char* 的区别见 05_void_vs_char_ptr.c。 */
    printf("\n=== 1.2 它们的柜子编号(地址) ===\n");
    printf("  &c = %p\n", (void *) &c);
    printf("  &x = %p\n", (void *) &x);
    printf("  &d = %p\n", (void *) &d); //%p 标准对应的类型是(void *)
    printf("  &d = %p\n", (char *) &d); //结果与(void *)一样，只是表示将这个结果转成了什么类型，需要转成什么类型取决于后面需要对其进行什么操作
    printf("[char*]  &d + 1 = %p\n", (char *) &d + 1); // 结果 =  (void *) &d + 1，因为char占1字节
    printf("  &d = %p\n", (int *) &d); //结果与(void *)一样
    printf("[int*]  &d + 1 = %p\n", (int *) &d + 1); //  结果 = (void *) &d + 4，因为int占4字节
    printf("  &d = %p\n", &d); // 不转默认其实是(参数类型 *)，这里即(double *)，因为d是double类型，即double * pd = &d
    printf("[default]  &d = %p\n", &d + 1); // 结果 = (void *) &d + 8，证明了 &d 是 double类型
    printf("  (数字每次运行都不一样，这很正常——操作系统每次分的位置不同)\n");

    printf("\n=== 1.3 三个变量挨得有多近 ===\n");
    /* 把地址转成 char* 再相减，就能算出"隔了几个柜子"。
     * 为什么必须转 char*？因为 char 正好占 1 个柜子，相减的结果单位就是"柜子数"。
     * 若直接 &x - &c 会编译报错（类型不同）；若两个同类型指针相减，
     * 得到的是"隔了几个元素"，不是"隔了几个字节"。
     * 完整解释见 05_void_vs_char_ptr.c。 */

    /*
     * 结果为负数的原因: c、x、d 是 main 里的局部变量，住在栈上。你这台 Apple Silicon 上，栈从高地址往低地址长。
     * 编译器又按声明顺序往下排：先 c（更高）、再 x、再 d（更低）。
     * 为什么是 -7，-12 ；暂时存疑，没理解清楚 填充位 的原理
     */
    printf("  从 &c 到 &x 隔了 %td 个柜子\n", (char *) &x - (char *) &c); // -7
    printf("  从 &x 到 &d 隔了 %td 个柜子\n", (char *) &d - (char *) &x); // -12


    printf("\n=== 1.4 数组：一排连号的柜子 ===\n");
    /* int arr[5] = 一次划走 5 个 int，也就是 5*4 = 20 个连着的柜子，然后按从低到高的地址分配每个元素 */
    int arr[5] = {10, 20, 30, 40, 50};

    printf("  arr 一共占 %zu 个柜子 (5 个 int × 4)\n", sizeof(arr));
    for (int i = 0; i < 5; i++) {
        /* arr[i] 是第 i 个元素的值，&arr[i] 是它的柜子编号 */
        printf("  arr[%d] = %2d   地址 = %p\n", i, arr[i], (void *) &arr[i]);
    }
    printf("  ^ 注意数组地址是每次 +4 递增的，因为一个 int 占 4 个柜子，紧挨着排\n");

    printf("\n=== 1.5 一个字节能存什么 ===\n");
    /* char 就是 1 个柜子，本质上存的是 0~255 的数字。
     * 'A' 其实就是数字 65，字符和数字在 C 里是一回事。 */
    printf("  c = '%c'，它在柜子里其实是数字 %d\n", c, c);
    printf("  'A'=%d 'B'=%d 'a'=%d '0'=%d\n", 'A', 'B', 'a', '0');

    return 0;
}

