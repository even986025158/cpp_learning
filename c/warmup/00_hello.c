/* ============================================================
 * 第 0 课：一个 C 程序长什么样
 * ============================================================
 *
 * 编译运行：
 *   cc -o 00_hello 00_hello.c        <- cc 是编译器，把 .c 变成可执行文件
 *   ./00_hello                        <- 运行它
 *
 * 逐行拆解见下面注释。
 */

/* #include 意思是"把别人写好的工具箱搬进来"。
 * stdio 是 STanDard Input/Output（标准输入输出）的缩写。
 * printf 这个"打印"功能就住在这个工具箱里，不 include 就用不了。 */
#include <stdio.h>

/* int main(void) { ... } 是程序的入口。
 * 操作系统运行你的程序时，就是从 main 的第一行开始执行。
 *   int   = main 结束时会交回一个整数（0 表示"一切正常"）
 *   main  = 固定名字，不能改
 *   void  = 括号里写 void 意思是"我不需要参数"
 *   { }   = 大括号框住的就是"函数体"，也就是要执行的步骤
 */
int main(void)
{
    /* 1) 定义变量：告诉编译器"我要一块地方，叫 age，里面放整数"
     *    int 是 integer（整数）。分号 ; 表示这句话结束了，C 里每句都要有。 */
    int age = 30;

    /* 2) printf 打印东西。双引号里是"模板"，% 开头的是"占位符"：
     *      %d  = 这里填一个整数(d = decimal 十进制)
     *      %f  = 这里填一个小数
     *      %c  = 这里填一个字符
     *      %s  = 这里填一串字符
     *      \n  = 换行（不写的话所有输出会挤在一行）
     *    逗号后面按顺序给出要填进占位符的值。 */
    printf("age = %d\n", age);

    /* 3) 变量可以改 */
    age = 31;
    printf("改了以后 age = %d\n", age);

    /* 4) 几种最常用的类型 */
    int    n = 100;         /* 整数，通常 4 字节 */
    char   c = 'A';         /* 一个字符，1 字节。注意单引号 */
    double d = 3.14;        /* 小数，8 字节 */

    printf("n = %d, c = %c, d = %f\n", n, c, d);

    /* 5) sizeof 是个"问工具"：问某个东西占多少字节。
     *    字节(byte) 是内存的最小计量单位，1 字节 = 8 个 0/1。
     *    %zu 是 sizeof 结果专用的占位符，你先当固定搭配记住。 */
    printf("int 占 %zu 字节, char 占 %zu 字节, double 占 %zu 字节\n",
           sizeof(int), sizeof(char), sizeof(double));

    /* 6) return 0 表示"我正常结束了"，交回给操作系统 */
    return 0;
}

