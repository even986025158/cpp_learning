/* ============================================================
 * 第 5 课的配件：一个"事后才出现"的函数
 * ============================================================
 *
 * 这个文件会被单独编译成一个动态库（.so / .dylib），
 * 【不会】和第 5 课的主程序链接在一起。
 *
 * 这一点是整节课的关键：主程序编译、链接、跑起来的时候，
 * 这个文件甚至可以还不存在。
 *
 * ★ 对照 PG：这就是你写一个 C 扩展时的样子。
 *   PostgreSQL 这个二进制早在几年前就编译好了，
 *   而你今天新写的函数，它必须也能调起来。
 */
#include <stdint.h>

/* 签名要和主程序约定的一致（第 4 课讲的"统一签名"）。
 * 这里为了让 demo 自包含，简化成 int64_t(int64_t, int64_t)。 */
int64_t plugin_add(int64_t a, int64_t b)
{
    return a + b;
}

int64_t plugin_mul(int64_t a, int64_t b)
{
    return a * b;
}
