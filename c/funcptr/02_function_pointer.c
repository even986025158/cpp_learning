/* ============================================================
 * 第 2 课：函数指针 = 专门存"函数编号"的变量
 * ============================================================
 *
 * 上一课：函数有编号。
 * 这一课：把那个编号**存进一个变量**。
 *
 * 对比着记（左边你已经会了）：
 *
 *   int   x = 5;        int  *p  = &x;     p 存"数据柜子"的编号
 *   int add(int,int);   int (*f)(int,int) = add;   f 存"代码柜子"的编号
 *
 * 声明语法确实丑，拆开读就不难：
 *
 *        int (*f)(int, int)
 *             ^^
 *             先看这里：f 是一个指针
 *        ^^^     ^^^^^^^^^^
 *        顺着它找过去，那东西是个「吃两个 int、还回一个 int」的函数
 *
 * ⚠️ 括号不能省。写成 int *f(int, int) 意思完全变了 ——
 *    那是"一个返回 int* 的普通函数"，不是指针变量。
 */
#include <stdio.h>

int add(int a, int b) { return a + b; }
int sub(int a, int b) { return a - b; }
int mul(int a, int b) { return a * b; }

int main(void)
{
    printf("=== 2.1 把函数编号存进变量 ===\n");

    int (*f)(int, int) = add;   /* f 现在存着 add 的编号 */

    /* 调用方式有两种写法，效果完全一样： */
    printf("  f(2, 3)    = %d   <- 简写，最常用\n", f(2, 3));
    printf("  (*f)(2, 3) = %d   <- 完整写法：先解引用，再调用\n", (*f)(2, 3));

    /* 为什么两种都行？
     * 因为 C 规定：调用时函数指针会自动"解引用"。
     * 就像 warmup/02 里 *p 是"顺着编号去看那个柜子"，
     * (*f)(2,3) 就是"顺着编号找到那段代码，然后执行它"。
     * 既然自动做，大家就都省着不写了。 */

    printf("\n=== 2.2 ★ 同一行调用代码，跑出不同的函数 ===\n");
    printf("   （这是函数指针存在的全部意义，请盯着看）\n");

    f = add;
    printf("  f = add 之后， f(10, 3) = %d\n", f(10, 3));

    f = sub;
    printf("  f = sub 之后， f(10, 3) = %d\n", f(10, 3));

    f = mul;
    printf("  f = mul 之后， f(10, 3) = %d\n", f(10, 3));

    printf("\n  注意：上面三次调用，写的都是同一句 f(10, 3)。\n");
    printf("  【究竟执行哪段代码，是由 f 里存的编号决定的，不是由这行代码决定的。】\n");

    printf("\n=== 2.3 于是「执行什么」可以由运行时数据决定 ===\n");
    /* 下面这个 choice 假装是从用户输入 / 配置文件 / 数据库里读来的。
     * 关键在于：编译器在编译这段代码时，根本不知道会跑哪个函数。 */
    for (int choice = 0; choice < 3; choice++) {
        int (*picked)(int, int) = (choice == 0) ? add
                                : (choice == 1) ? sub
                                                : mul;
        printf("  choice=%d -> 结果 %d\n", choice, picked(10, 3));
    }

    printf("\n【记住这一句】函数指针让「调用哪个函数」从\n");
    printf("  编译期写死  变成了  运行期可换。\n");
    printf("PG 需要的正是这个能力 —— 原因在第 5 课揭晓。\n");

    return 0;
}
