/* ============================================================
 * 宏第 2 课：带参数的宏 ≈ 会粘贴的「伪函数」
 * ============================================================
 *
 * #define SQUARE(x) ((x) * (x))
 *
 * 看起来像函数，但仍然是文字替换：
 *   SQUARE(3)     先变成  ((3) * (3))
 *   SQUARE(1+2)   先变成  ((1+2) * (1+2))
 *
 * Java 里方法调用会先把参数算完再传入。
 * 宏不会：它把你写的那几个字符原样贴进去，所以括号极其重要。
 *
 * 对比下面 BAD 和 GOOD，先预测两行输出，再运行。
 */
#include <stdio.h>

#define SQUARE_BAD(x)  x * x
#define SQUARE(x)      ((x) * (x))

int main(void)
{
    printf("=== 2.1 缺括号会算错 ===\n");
    printf("  SQUARE_BAD(1+2) = %d   <- 预测：是 9 还是 5？\n", SQUARE_BAD(1 + 2));
    printf("  SQUARE(1+2)     = %d   <- 这个才是 (1+2)*(1+2)\n", SQUARE(1 + 2));

    /* SQUARE_BAD(1+2) 替换成： 1+2 * 1+2
     * 乘法优先，变成 1 + 2 + 2 = 5，不是 9。 */

    printf("\n=== 2.2 参数会被贴两次，副作用会执行两次 ===\n");
    int i = 2;
    int r = SQUARE(i++);
    /*
     * SQUARE(i++) 的结果 r = 6, 之后 i = 4
     * 因为 i++ 先传参再++，
     * 所以 SQUARE(i++) = 2 * 3
     * 1. 第一个x = i++; 此时 x = 2，i = 3
     * 2. 第二个x = i++; 此时 x = 3，i = 4
     */
    printf("  SQUARE(i++) 的结果 r = %d, 之后 i = %d\n", r, i);
    printf("  （如果是真函数，i 只会 +1；宏把 i++ 贴了两份）\n");

    return 0;
}

