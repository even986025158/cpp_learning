/* ============================================================
 * 宏第 1 课：#define 就是「编译之前的文字替换」
 * ============================================================
 *
 * 先记住流水线（D01 做过，这里只取第一步）：
 *
 *   .c 文件  --预处理-->  普通 C 文本  --编译-->  机器码
 *
 * 以 # 开头的行（#include / #define / #ifndef ...）不是给编译器的，
 * 是给「预处理器」的。它先改文本，编译器看到的是改完之后的结果。
 *
 * #define 名字 替换内容
 * 意思：后面凡是单独出现的「名字」，先换成「替换内容」，再拿去编译。
 *
 * 它不是 Java 的变量，也不是常量对象：替换时不算、不分配内存，
 * 只是改字。所以 MAX 不是一个柜子，只是「请写成 100」的便利贴。
 *
 * 看完先自己预测输出，再运行对照。
 * 然后用下面这条看「编译器真正拿到的文本」（本日最重要的命令）：
 *
 *   clang -E -P 01_define_replace.c | less
 *
 * -E = 只预处理，不编译
 * -P = 少打一些行号噪音，方便人看
 */
#include <stdio.h>

#define MAX 100
#define GREETING "hello"

int main(void)
{
    int x = MAX;
    int y = MAX + 1;

    printf("x = %d, y = %d\n", x, y);
    printf("GREETING = %s\n", GREETING);

    /* 预处理器不管算术，它不会先把 MAX+1 算成 101。
     * 它只是把 MAX 四个字母换成 100，变成：int y = 100 + 1;
     * 加法是编译器后来才做的。 */

    return 0;
}

